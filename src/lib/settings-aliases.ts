/** 取某一行标题对应的别名；没登记就返回空数组 */
export function aliasesFor(label: string): string[] {
  return SETTING_ALIASES[label] ?? [];
}

/**
 * dev 下校验：别名表的键是否都还能对上真实存在的设置行标题。
 * 行改名后别名会静默失效，这个检查把它变成看得见的告警。
 */
export function warnStaleAliasKeys(labels: Set<string>): void {
  const stale = Object.keys(SETTING_ALIASES).filter((k) => !labels.has(k));
  if (stale.length > 0) {
    console.warn("[设置搜索] 别名表里这些键已找不到对应的设置行（可能改过名），它们的别名不会生效：", stale);
  }
}
